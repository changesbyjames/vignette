import { mkdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";

import { bundle } from "../bundle/bundle.js";
import { loadVite } from "../bundle/load-vite.js";
import { previewEntry, previewHtml } from "../vite/pages.js";

/** Options of {@link runBuild}. */
export interface RunBuildOptions {
  /** The show module; its default export is the `<Show>`. */
  readonly show: string;
  /** Output directory; usually `dist`. */
  readonly out: string;
}

const PREVIEW_ID = "\0vignette:preview";

/**
 * `vignette build`: everything a production host needs, in `out`.
 *
 * ```
 * out/
 *   server.js   # node out/server.js — serves /, /stream and /vignette/*
 *   show.js     # the show compiled for Node; bare imports stay imports
 *   public/     # what `bundle` writes, plus the preview page (preview.html, preview.js)
 * ```
 *
 * The show is compiled with Vite's SSR build, so `out` must stay inside the project: `show.js`
 * and `server.js` import `@strangecyan/vignette` and React from its `node_modules`.
 */
export async function runBuild(options: RunBuildOptions): Promise<void> {
  const show = resolve(options.show);
  const root = dirname(show);
  const out = resolve(options.out);
  const publicDir = join(out, "public");
  await bundle(show, { out: publicDir });
  await buildPreview(root, previewEntry("/stream"), publicDir);
  await writeFile(join(publicDir, "preview.html"), previewHtml());
  await buildShow(root, show, out);
  await mkdir(out, { recursive: true });
  await writeFile(join(out, "server.js"), SERVER_SOURCE);
}

/** Compiles the preview page's module, with React DOM, into `preview.js`. */
async function buildPreview(root: string, entry: string, out: string): Promise<void> {
  const { build } = await loadVite();
  await build({
    root,
    configFile: false,
    envDir: false,
    publicDir: false,
    logLevel: "warn",
    mode: "production",
    // Production JSX whatever NODE_ENV says: Vite picks jsxDEV from the ambient NODE_ENV only.
    oxc: { jsx: { development: false } },
    define: { "process.env.NODE_ENV": '"production"' },
    resolve: { dedupe: ["react", "react-dom"] },
    plugins: [
      {
        name: "vignette:preview-entry",
        resolveId: (id) => (id === PREVIEW_ID ? PREVIEW_ID : undefined),
        load: (id) => (id === PREVIEW_ID ? entry : undefined),
      },
    ],
    build: {
      outDir: out,
      emptyOutDir: false,
      copyPublicDir: false,
      modulePreload: false,
      assetsInlineLimit: Number.MAX_SAFE_INTEGER,
      rolldownOptions: {
        input: PREVIEW_ID,
        output: { format: "es", entryFileNames: "preview.js", codeSplitting: false },
      },
    },
  });
}

/** Compiles the show and its local imports to `out/show.js`; packages stay external. */
async function buildShow(root: string, show: string, out: string): Promise<void> {
  const { build } = await loadVite();
  await build({
    root,
    configFile: false,
    envDir: false,
    publicDir: false,
    logLevel: "warn",
    mode: "production",
    // Production JSX whatever NODE_ENV says: Vite picks jsxDEV from the ambient NODE_ENV only.
    oxc: { jsx: { development: false } },
    ssr: { external: true },
    build: {
      ssr: show,
      outDir: out,
      emptyOutDir: false,
      copyPublicDir: false,
      rolldownOptions: {
        output: { format: "es", entryFileNames: "show.js", codeSplitting: false },
      },
    },
  });
}

/** `out/server.js`: the README's step-by-step host, on `node:http`. */
const SERVER_SOURCE = `// Generated by \`vignette build\`. Run with \`node server.js\`.
//
//   PORT           port to listen on (default 4173)
//   HOST           interface to listen on (default: all)
//   PUBLIC_ORIGIN  the URL targets reach this server at (default http://127.0.0.1:<PORT>);
//                  published in the stream so OBS can find the frame page and assets
import { createReadStream } from "node:fs";
import { readFile, stat } from "node:fs/promises";
import { createServer } from "node:http";
import { extname, isAbsolute, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compose, encodeStreamMessageSse, streamOptions } from "@strangecyan/vignette";

import show from "./show.js";

const publicDir = fileURLToPath(new URL("./public/", import.meta.url));
const port = Number(process.env.PORT ?? 4173);
const origin = (process.env.PUBLIC_ORIGIN ?? \`http://127.0.0.1:\${port}\`).replace(/\\/$/, "");

const composer = compose(show, {
  assets: JSON.parse(await readFile(join(publicDir, "assets.json"), "utf8")),
  serve: {
    stream: \`\${origin}/stream\`,
    assets: \`\${origin}/vignette/assets/\`,
    frames: \`\${origin}/vignette/frames.html\`,
  },
  onError: (error) => console.error(error),
});
await composer.ready();

const server = createServer(async (request, response) => {
  try {
    const path = decodeURIComponent(new URL(request.url ?? "/", "http://host").pathname);
    if (path === "/stream") await stream(request, response);
    else if (path === "/") await send(response, join(publicDir, "preview.html"));
    else if (path.startsWith("/vignette/")) await send(response, resolve(publicDir, \`.\${path.slice(9)}\`));
    else notFound(response);
  } catch (error) {
    console.error(error);
    if (!response.headersSent) response.writeHead(500);
    response.end();
  }
});

/** Server-sent events: setup and the latest update, then every message as it happens. */
async function stream(request, response) {
  const abort = new AbortController();
  response.on("close", () => abort.abort());
  response.writeHead(200, { "content-type": "text/event-stream", "cache-control": "no-cache" });
  for await (const message of composer.stream(abort.signal, streamOptions(request.url))) {
    response.write(encodeStreamMessageSse(message));
  }
  response.end();
}

const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json",
  ".css": "text/css; charset=utf-8",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".gif": "image/gif",
  ".webp": "image/webp",
  ".svg": "image/svg+xml",
  ".mp4": "video/mp4",
  ".webm": "video/webm",
  ".mp3": "audio/mpeg",
  ".woff2": "font/woff2",
};

/** A file from \`public/\`, never outside it. */
async function send(response, file) {
  const inside = relative(publicDir, file);
  const found = !inside.startsWith("..") && !isAbsolute(inside) && (await isFile(file));
  if (!found) return notFound(response);
  const type = types[extname(file).toLowerCase()] ?? "application/octet-stream";
  response.writeHead(200, { "content-type": type });
  createReadStream(file).pipe(response);
}

async function isFile(file) {
  return stat(file).then((info) => info.isFile(), () => false);
}

function notFound(response) {
  response.writeHead(404, { "content-type": "text/plain" });
  response.end("Not found");
}

server.listen(port, process.env.HOST, () => {
  console.log(\`vignette: preview at \${origin}/, stream at \${origin}/stream\`);
});

for (const signal of ["SIGINT", "SIGTERM"]) {
  process.once(signal, () => {
    composer.dispose();
    server.close();
    server.closeAllConnections();
  });
}
`;
